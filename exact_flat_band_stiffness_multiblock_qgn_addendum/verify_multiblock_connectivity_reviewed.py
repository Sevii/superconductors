def print_model_summary(model: Model) -> tuple[int, int, int]:
    generators = model.generators
    associative = associative_closure(generators)
    lie = lie_closure([1j * generator for generator in generators])
    rank = int(np.linalg.matrix_rank(model.profile, tol=TOL))

    print(f"\n{model.name}")
    print("-" * len(model.name))
    for a, (vectors, projectors, dim) in enumerate(
        zip(model.vectors_by_block, model.projectors_by_block, model.block_dims, strict=True)
    ):
        tight = sum(projectors)
        c = np.trace(tight).real / dim
        print(f"Block {a}: dim={dim}, tight error={np.linalg.norm(tight-c*np.eye(dim)):.3e}, "
              f"connected={frame_graph_connected(vectors)}")
    print("Trace profile:\n", model.profile)
    print("Trace-profile rank:", rank)
    print("Complex associative dimension:", len(associative))
    print("Real Lie dimension:", len(lie))
    return len(associative), len(lie), rank


def check_counterexample_center_membership(model: Model) -> None:
    lie = lie_closure([1j * generator for generator in model.generators])
    total_center = 1j * block_diag([np.eye(2), np.eye(2)])
    relative_center = 1j * block_diag([np.eye(2), -np.eye(2)])
    total_residual = span_residual(lie, total_center, real=True)
    relative_residual = span_residual(lie, relative_center, real=True)
    print("Total-center membership residual:", f"{total_residual:.3e}")
    print("Relative-center membership residual:", f"{relative_residual:.3e}")
    assert total_residual < 1.0e-9
    assert relative_residual > 1.0e-3

    # Explicit determinant dark states.  Ordering is
    # A-up(0,1), B-up(2,3), A-down(4,5), B-down(6,7).
    number_particles = 4
    masks = [
        (1 << 0) | (1 << 1) | (1 << 6) | (1 << 7),
        (1 << 2) | (1 << 3) | (1 << 4) | (1 << 5),
    ]
    max_residual = 0.0
    for generator in model.generators:
        signed = np.zeros((8, 8), dtype=complex)
        signed[:4, :4] = generator
        signed[4:, 4:] = -generator.conj()
        factor, basis = second_quantize(signed, number_particles)
        index = {mask: position for position, mask in enumerate(basis)}
        for mask in masks:
            state = np.zeros(len(basis), dtype=complex)
            state[index[mask]] = 1.0
            max_residual = max(max_residual, float(np.linalg.norm(factor @ state)))
    print("Explicit determinant-state factor residual:", f"{max_residual:.3e}")
    assert max_residual < 1.0e-12


def total_nullities(model: Model) -> list[int]:
    totals = []
    for number_particles in range(2 * sum(model.block_dims) + 1):
        hamiltonian, _ = qgn_hamiltonian(model.generators, number_particles)
        totals.append(nullity(hamiltonian))
    return totals


def main() -> None:
    counterexample = make_two_block_model(
        "Counterexample: full *-algebra but missing relative center",
        theta_a=math.pi / 4.0,
        theta_b=math.pi / 6.0,
        weights_a=(0.5, 0.5),
        weights_b=(0.5, 0.5),
    )
    assoc, lie_dim, trace_rank = print_model_summary(counterexample)
    assert gram_mismatch(
        counterexample.projectors_by_block[0], counterexample.projectors_by_block[1]
    ) > 1.0e-3
    assert (assoc, lie_dim, trace_rank) == (8, 7, 1)
    check_counterexample_center_membership(counterexample)
    totals = compare_every_charge_sector(
        counterexample.name,
        counterexample.generators,
        counterexample.block_dims,
        counterexample.profile,
        counterexample.synchronization_classes,
    )
    print("All-sector nullities N=0,...,8:", totals)
    assert totals == [1, 0, 2, 0, 5, 0, 2, 0, 1]

    repaired = make_two_block_model(
        "Repaired model: full trace rank and exact product-AGP manifold",
        theta_a=math.pi / 4.0,
        theta_b=math.pi / 6.0,
        weights_a=(1.0 / 3.0, 2.0 / 3.0),
        weights_b=(2.0 / 3.0, 1.0 / 3.0),
    )
    assoc, lie_dim, trace_rank = print_model_summary(repaired)
    assert (assoc, lie_dim, trace_rank) == (8, 8, 2)
    totals = compare_every_charge_sector(
        repaired.name,
        repaired.generators,
        repaired.block_dims,
        repaired.profile,
        repaired.synchronization_classes,
    )
    print("All-sector nullities N=0,...,8:", totals)
    assert totals == [1, 0, 2, 0, 3, 0, 2, 0, 1]

    synchronized = make_two_block_model(
        "Synchronized control",
        theta_a=math.pi / 4.0,
        theta_b=math.pi / 4.0,
        weights_a=(0.5, 0.5),
        weights_b=(0.5, 0.5),
        synchronized=True,
    )
    assoc, lie_dim, trace_rank = print_model_summary(synchronized)
    assert gram_mismatch(
        synchronized.projectors_by_block[0], synchronized.projectors_by_block[1]
    ) < TOL
    assert (assoc, lie_dim, trace_rank) == (4, 4, 1)
    totals = compare_every_charge_sector(
        synchronized.name,
        synchronized.generators,
        synchronized.block_dims,
        synchronized.profile,
        synchronized.synchronization_classes,
    )
    print("All-sector nullities N=0,...,8:", totals)
    assert totals == [1, 0, 4, 0, 10, 0, 4, 0, 1]

    vectors_two, projectors_two, vectors_three, projectors_three = unequal_capacity_frames()
    unequal = Model(
        "Unequal capacities: center deficit without determinant resonance",
        (2, 3),
        (tuple(vectors_two), tuple(vectors_three)),
        (tuple(projectors_two), tuple(projectors_three)),
        ((0,), (1,)),
    )
    assoc, lie_dim, trace_rank = print_model_summary(unequal)
    assert (assoc, lie_dim, trace_rank) == (13, 12, 1)
    totals = compare_every_charge_sector(
        unequal.name,
        unequal.generators,
        unequal.block_dims,
        unequal.profile,
        unequal.synchronization_classes,
    )
    print("All-sector nullities N=0,...,10:", totals)
    assert totals == [1, 0, 2, 0, 3, 0, 3, 0, 2, 0, 1]

    odd = make_odd_resonance_model()
    assoc, lie_dim, trace_rank = print_model_summary(odd)
    assert (assoc, lie_dim, trace_rank) == (5, 4, 1)
    totals = compare_every_charge_sector(
        odd.name,
        odd.generators,
        odd.block_dims,
        odd.profile,
        odd.synchronization_classes,
    )
    print("All-sector nullities N=0,...,6:", totals)
    assert totals == [1, 0, 2, 2, 2, 0, 1]

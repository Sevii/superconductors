# One-body frames and linear closures
# ---------------------------------------------------------------------------


def two_basis_frame(theta: float, first_weight: float, second_weight: float):
    """Two weighted orthonormal bases in C^2."""
    e1 = np.array([1.0, 0.0], dtype=complex)
    e2 = np.array([0.0, 1.0], dtype=complex)
    f1 = np.array([math.cos(theta), math.sin(theta)], dtype=complex)
    f2 = np.array([-math.sin(theta), math.cos(theta)], dtype=complex)
    vectors = [
        math.sqrt(first_weight) * e1,
        math.sqrt(first_weight) * e2,
        math.sqrt(second_weight) * f1,
        math.sqrt(second_weight) * f2,
    ]
    return vectors, [np.outer(v, v.conj()) for v in vectors]


def frame_graph_connected(vectors: Sequence[np.ndarray], tol: float = TOL) -> bool:
    active = [i for i, v in enumerate(vectors) if np.vdot(v, v).real > tol]
    if not active:
        return False
    adjacency = {i: [] for i in active}
    for i, j in itertools.combinations(active, 2):
        if abs(np.vdot(vectors[i], vectors[j])) > tol:
            adjacency[i].append(j)
            adjacency[j].append(i)
    seen = {active[0]}
    queue = deque([active[0]])
    while queue:
        i = queue.popleft()
        for j in adjacency[i]:
            if j not in seen:
                seen.add(j)
                queue.append(j)
    return len(seen) == len(active)


def real_vector(matrix: np.ndarray) -> np.ndarray:
    return np.concatenate((matrix.real.ravel(), matrix.imag.ravel()))


def add_if_independent(
    basis: list[np.ndarray], candidate: np.ndarray, *, real: bool, tol: float = TOL
) -> bool:
    vector = real_vector(candidate) if real else candidate.ravel()
    if not basis:
        basis.append(candidate)
        return True
    columns = [real_vector(item) if real else item.ravel() for item in basis]
    design = np.column_stack(columns)
    coefficients, *_ = np.linalg.lstsq(design, vector, rcond=None)
    residual = np.linalg.norm(vector - design @ coefficients)
    if residual > tol:
        basis.append(candidate)
        return True
    return False


def span_residual(basis: Sequence[np.ndarray], target: np.ndarray, *, real: bool) -> float:
    if not basis:
        return float(np.linalg.norm(target))
    vector = real_vector(target) if real else target.ravel()
    design = np.column_stack(
        [real_vector(item) if real else item.ravel() for item in basis]
    )
    coefficients, *_ = np.linalg.lstsq(design, vector, rcond=None)
    return float(np.linalg.norm(vector - design @ coefficients))


def associative_closure(generators: Sequence[np.ndarray]) -> list[np.ndarray]:
    """Complex linear span of the unital algebra generated by matrices."""
    dimension = generators[0].shape[0]
    basis: list[np.ndarray] = []
    add_if_independent(basis, np.eye(dimension, dtype=complex), real=False)
    for generator in generators:
        add_if_independent(basis, generator, real=False)
    changed = True
    while changed:
        changed = False
        snapshot = list(basis)
        for left in snapshot:
            for right in generators:
                changed |= add_if_independent(basis, left @ right, real=False)
                changed |= add_if_independent(basis, right @ left, real=False)
    return basis


def lie_closure(generators: Sequence[np.ndarray]) -> list[np.ndarray]:
    """Real Lie algebra generated by skew-Hermitian matrices."""
    basis: list[np.ndarray] = []
    for generator in generators:
        add_if_independent(basis, generator, real=True)
    changed = True
    while changed:
        changed = False
        snapshot = list(basis)
        for index, left in enumerate(snapshot):
            for right in snapshot[index + 1 :]:
                changed |= add_if_independent(
                    basis, left @ right - right @ left, real=True
                )
    return basis


def block_diag(blocks: Sequence[np.ndarray]) -> np.ndarray:
    size = sum(block.shape[0] for block in blocks)
    out = np.zeros((size, size), dtype=complex)
    start = 0
    for block in blocks:
        stop = start + block.shape[0]
        out[start:stop, start:stop] = block
        start = stop
    return out


def block_generators(projectors_by_block: Sequence[Sequence[np.ndarray]]) -> list[np.ndarray]:
    number_labels = len(projectors_by_block[0])
    assert all(len(block) == number_labels for block in projectors_by_block)
    return [
        block_diag([projectors_by_block[a][lam] for a in range(len(projectors_by_block))])
        for lam in range(number_labels)
    ]


def trace_profile(projectors_by_block: Sequence[Sequence[np.ndarray]]) -> np.ndarray:
    dims = [block[0].shape[0] for block in projectors_by_block]
    number_labels = len(projectors_by_block[0])
    return np.array(
        [
            [
                np.trace(projectors_by_block[a][lam]).real / dims[a]
                for a in range(len(dims))
            ]
            for lam in range(number_labels)
        ],
        dtype=float,
    )


def gram_mismatch(
    projectors_a: Sequence[np.ndarray], projectors_b: Sequence[np.ndarray]
) -> float:
    gram_a = np.array(
        [[np.trace(x @ y).real for y in projectors_a] for x in projectors_a]
    )
    gram_b = np.array(
        [[np.trace(x @ y).real for y in projectors_b] for x in projectors_b]
    )
    return float(np.max(np.abs(gram_a - gram_b)))



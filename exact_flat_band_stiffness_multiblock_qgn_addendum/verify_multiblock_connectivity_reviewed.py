def fermion_basis(number_orbitals: int, number_particles: int) -> list[int]:
    return [
        sum(1 << orbital for orbital in occupied)
        for occupied in itertools.combinations(range(number_orbitals), number_particles)
    ]


def annihilate(mask: int, orbital: int):
    if not ((mask >> orbital) & 1):
        return None
    sign = -1 if (mask & ((1 << orbital) - 1)).bit_count() % 2 else 1
    return sign, mask ^ (1 << orbital)


def create(mask: int, orbital: int):
    if (mask >> orbital) & 1:
        return None
    sign = -1 if (mask & ((1 << orbital) - 1)).bit_count() % 2 else 1
    return sign, mask ^ (1 << orbital)


def second_quantize(one_body: np.ndarray, number_particles: int):
    number_orbitals = one_body.shape[0]
    basis = fermion_basis(number_orbitals, number_particles)
    index = {mask: position for position, mask in enumerate(basis)}
    operator = np.zeros((len(basis), len(basis)), dtype=complex)
    for column, mask in enumerate(basis):
        for source in range(number_orbitals):
            removed = annihilate(mask, source)
            if removed is None:
                continue
            sign_a, intermediate = removed
            for target in range(number_orbitals):
                amplitude = one_body[target, source]
                if abs(amplitude) <= 1.0e-15:
                    continue
                inserted = create(intermediate, target)
                if inserted is None:
                    continue
                sign_c, final = inserted
                operator[index[final], column] += sign_a * sign_c * amplitude
    return operator, basis


def qgn_hamiltonian(one_spin_generators: Sequence[np.ndarray], number_particles: int):
    one_spin_dimension = one_spin_generators[0].shape[0]
    factor_matrices = []
    basis = None
    for one_spin in one_spin_generators:
        signed = np.zeros((2 * one_spin_dimension, 2 * one_spin_dimension), dtype=complex)
        signed[:one_spin_dimension, :one_spin_dimension] = one_spin
        signed[one_spin_dimension:, one_spin_dimension:] = -one_spin.conj()
        factor, basis = second_quantize(signed, number_particles)
        factor_matrices.append(factor)
    hamiltonian = sum(factor.conj().T @ factor for factor in factor_matrices) / 2.0
    return hamiltonian, basis


def nullity(matrix: np.ndarray, tol: float = TOL) -> int:
    if matrix.size == 0:
        return 0
    eigenvalues = np.linalg.eigvalsh(matrix)
    return int(np.count_nonzero(eigenvalues < tol))


def charge_tuple(mask: int, block_dims: Sequence[int]) -> tuple[int, ...]:
    one_spin_dimension = sum(block_dims)
    groups: list[range] = []
    start = 0
    for dim in block_dims:
        groups.append(range(start, start + dim))
        start += dim
    start = one_spin_dimension
    for dim in block_dims:
        groups.append(range(start, start + dim))
        start += dim
    return tuple(sum((mask >> orbital) & 1 for orbital in group) for group in groups)


def charge_sector_nullities(
    hamiltonian: np.ndarray, basis: Sequence[int], block_dims: Sequence[int]
) -> dict[tuple[int, ...], int]:
    sectors: dict[tuple[int, ...], list[int]] = defaultdict(list)
    for index, mask in enumerate(basis):
        sectors[charge_tuple(mask, block_dims)].append(index)
    output: dict[tuple[int, ...], int] = {}
    for sector, indices in sectors.items():
        restricted = hamiltonian[np.ix_(indices, indices)]
        sector_nullity = nullity(restricted)
        if sector_nullity:
            output[sector] = sector_nullity
    return output



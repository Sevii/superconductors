def su2_tensor_multiplicities(occupations: Sequence[int]) -> dict[int, int]:
    """SU(2) multiplicities for products of Lambda^r C^2.

    Keys are twice the spin.  Lambda^0 and Lambda^2 are trivial; Lambda^1 is
    spin 1/2.  The routine is intentionally independent of the ED code.
    """
    multiplicities = {0: 1}
    for occupation in occupations:
        if occupation in (0, 2):
            factor = {0: 1}
        elif occupation == 1:
            factor = {1: 1}
        else:
            raise ValueError(f"invalid C^2 exterior power {occupation}")
        updated: dict[int, int] = defaultdict(int)
        for j1, m1 in multiplicities.items():
            for j2, m2 in factor.items():
                for j in range(abs(j1 - j2), j1 + j2 + 1, 2):
                    updated[j] += m1 * m2
        multiplicities = dict(updated)
    return multiplicities


def predicted_sector_nullity(
    sector: tuple[int, ...],
    block_dims: Sequence[int],
    profile: np.ndarray,
    synchronization_classes: Sequence[Sequence[int]],
    tol: float = TOL,
) -> int:
    q = len(block_dims)
    r = np.array(sector[:q], dtype=int)
    s = np.array(sector[q:], dtype=int)
    delta = r - s
    if np.linalg.norm(profile @ delta, ord=np.inf) > tol:
        return 0

    answer = 1
    for cls in synchronization_classes:
        dims = {block_dims[a] for a in cls}
        if len(dims) != 1:
            raise ValueError("synchronization classes must have one common dimension")
        L = dims.pop()
        if L == 1:
            # su(1) is trivial; one-dimensional blocks are controlled only by
            # the center condition above.
            factor = 1
        elif len(cls) == 1:
            a = cls[0]
            factor = int(r[a] == s[a] or {int(r[a]), int(s[a])} == {0, L})
        elif L == 2:
            mr = su2_tensor_multiplicities([int(r[a]) for a in cls])
            ms = su2_tensor_multiplicities([int(s[a]) for a in cls])
            factor = sum(mr.get(j, 0) * ms.get(j, 0) for j in set(mr) | set(ms))
        else:
            raise NotImplementedError(
                "the extended certificate only needs multi-block synchronization at L=2"
            )
        answer *= factor
        if answer == 0:
            break
    return answer


def compare_every_charge_sector(
    name: str,
    generators: Sequence[np.ndarray],
    block_dims: Sequence[int],
    profile: np.ndarray,
    synchronization_classes: Sequence[Sequence[int]],
) -> list[int]:
    total_modes = 2 * sum(block_dims)
    totals: list[int] = []
    for number_particles in range(total_modes + 1):
        hamiltonian, basis = qgn_hamiltonian(generators, number_particles)
        observed = charge_sector_nullities(hamiltonian, basis, block_dims)

        predicted: dict[tuple[int, ...], int] = {}
        q = len(block_dims)
        for r in itertools.product(*(range(L + 1) for L in block_dims)):
            for s in itertools.product(*(range(L + 1) for L in block_dims)):
                if sum(r) + sum(s) != number_particles:
                    continue
                sector = tuple(r + s)
                value = predicted_sector_nullity(
                    sector, block_dims, profile, synchronization_classes
                )
                if value:
                    predicted[sector] = value

        if observed != predicted:
            all_keys = sorted(set(observed) | set(predicted))
            details = [
                (key, observed.get(key, 0), predicted.get(key, 0))
                for key in all_keys
                if observed.get(key, 0) != predicted.get(key, 0)
            ]
            raise AssertionError(
                f"{name}: charge-sector mismatch at N={number_particles}: {details}"
            )
        totals.append(sum(observed.values()))
    return totals



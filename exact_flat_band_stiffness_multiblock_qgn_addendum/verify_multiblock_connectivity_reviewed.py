#!/usr/bin/env python3
"""Extended independent certificates for the multi-block QGN addendum v3.

This suite checks the joint Lie algebra, the complete charge-sector kernel
formula, the fixed-composition MB3 criterion, and the determinant-resonance
parity rule.  It includes the four v2 cases and two adversarial additions:

  * L=(1,2) with an odd-capacity resonance.  Every even sector is exactly the
    product-AGP span, while the three-particle sector contains two determinant
    dark states.
  * L=(1,2,2) with a synchronized pair of L=2 blocks and simultaneous even-
    and odd-capacity center resonances.  The theorem's charge-sector formula
    is compared against exact diagonalization in every sector N=0,...,10.

Only NumPy is required.
"""

from __future__ import annotations

import itertools
import math
from collections import defaultdict, deque
from dataclasses import dataclass
from typing import Callable, Iterable, Sequence

import numpy as np

TOL = 1.0e-10



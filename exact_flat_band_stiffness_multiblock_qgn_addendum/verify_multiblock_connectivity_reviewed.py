def scalar_block(weights: Sequence[float]):
    vectors = [np.array([math.sqrt(weight)], dtype=complex) for weight in weights]
    projectors = [np.array([[weight]], dtype=complex) for weight in weights]
    return vectors, projectors


def unequal_capacity_frames():
    """Connected tight frames in C^2 and C^3 with identical normalized traces."""
    vectors_two = []
    for theta in (0.0, math.pi / 4.0, math.pi / 8.0):
        vectors_two.extend(
            [
                np.array([math.cos(theta), math.sin(theta)], dtype=complex),
                np.array([-math.sin(theta), math.cos(theta)], dtype=complex),
            ]
        )
    vectors_two = [math.sqrt(1.0 / 3.0) * vector for vector in vectors_two]

    standard = np.eye(3, dtype=complex)
    omega = np.exp(2j * math.pi / 3.0)
    fourier = np.array(
        [[omega ** (row * column) for column in range(3)] for row in range(3)],
        dtype=complex,
    ) / math.sqrt(3.0)
    vectors_three = [standard[:, column] for column in range(3)]
    vectors_three.extend(fourier[:, column] for column in range(3))
    vectors_three = [math.sqrt(1.0 / 2.0) * vector for vector in vectors_three]

    return (
        vectors_two,
        [np.outer(v, v.conj()) for v in vectors_two],
        vectors_three,
        [np.outer(v, v.conj()) for v in vectors_three],
    )


@dataclass
class Model:
    name: str
    block_dims: tuple[int, ...]
    vectors_by_block: tuple[tuple[np.ndarray, ...], ...]
    projectors_by_block: tuple[tuple[np.ndarray, ...], ...]
    synchronization_classes: tuple[tuple[int, ...], ...]

    @property
    def generators(self) -> list[np.ndarray]:
        return block_generators(self.projectors_by_block)

    @property
    def profile(self) -> np.ndarray:
        return trace_profile(self.projectors_by_block)


def make_two_block_model(
    name: str,
    theta_a: float,
    theta_b: float,
    weights_a: tuple[float, float],
    weights_b: tuple[float, float],
    synchronized: bool = False,
) -> Model:
    vectors_a, projectors_a = two_basis_frame(theta_a, *weights_a)
    vectors_b, projectors_b = two_basis_frame(theta_b, *weights_b)
    classes = ((0, 1),) if synchronized else ((0,), (1,))
    return Model(
        name,
        (2, 2),
        (tuple(vectors_a), tuple(vectors_b)),
        (tuple(projectors_a), tuple(projectors_b)),
        classes,
    )


def make_odd_resonance_model() -> Model:
    vectors_a, projectors_a = scalar_block([0.5, 0.5, 0.5, 0.5])
    vectors_b, projectors_b = two_basis_frame(math.pi / 4.0, 0.5, 0.5)
    return Model(
        "Odd-F resonance: L=(1,2), Z=span(2,1)",
        (1, 2),
        (tuple(vectors_a), tuple(vectors_b)),
        (tuple(projectors_a), tuple(projectors_b)),
        ((0,), (1,)),
    )


def make_mixed_mechanism_model() -> Model:
    vectors_a, projectors_a = scalar_block([0.5, 0.5, 0.5, 0.5])
    vectors_b, projectors_b = two_basis_frame(math.pi / 4.0, 0.5, 0.5)
    # C is label-by-label identical to B, hence synchronized.
    vectors_c = [v.copy() for v in vectors_b]
    projectors_c = [p.copy() for p in projectors_b]
    return Model(
        "Mixed mechanisms: L=(1,2,2), synchronized {B,C}, Z=span(2,1,1)",
        (1, 2, 2),
        (tuple(vectors_a), tuple(vectors_b), tuple(vectors_c)),
        (tuple(projectors_a), tuple(projectors_b), tuple(projectors_c)),
        ((0,), (1, 2)),
    )


